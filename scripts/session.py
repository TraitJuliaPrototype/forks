"""The interactive workload (plan §4.2) in pandas, step by step as scripts/session.jl.
    DATA=data python scripts/session.py        # marks "T <step> <time>" on stdout
Results are printed as the Python prompt would display them (repr)."""
import time
def _m(s): print("T", s, repr(time.time()), flush=True)
_m("start")
import os, tempfile
import numpy as np, pandas as pd
_m("imports")
D = os.environ.get("DATA", "data"); tmp = tempfile.mktemp()
df = pd.read_csv(os.path.join(D, "people.csv"), parse_dates=["joined"])
_m("read")
print(repr(df))
_m("show")
print(repr(df.describe(include="all")))
_m("describe")
sub = df[["id", "city", "income"]]; sub = sub[sub.income.notna() & (sub.income > 5e4)]; print(repr(sub))
_m("select_filter")
print(repr(df.sort_values(["city", "income"], ascending=[True, False])))
_m("sort")
print(repr(df.groupby("city").agg(mean_income=("income", "mean"), nrow=("income", "size")).reset_index()))
_m("groupby_combine")
print(repr(df.assign(ratio=df.apply(lambda r: (0.0 if pd.isna(r.income) else r.income) / max(1 if pd.isna(r.age) else r.age, 1), axis=1))))
_m("user_function")
print(repr(df.merge(pd.read_csv(os.path.join(D, "orders.csv"), parse_dates=["ts"]), on="id")))
_m("join")
df["income_k"] = df.income / 1000
_m("add_column")
df.to_csv(tmp, index=False)
_m("write")
s2 = pd.read_csv(os.path.join(D, "sensors.csv")); print(repr(s2))
_m("2_read_show")
print(repr(s2.describe(include="all")))
_m("2_describe")
print(repr(s2.sort_values(["tag", "s1"])))
_m("2_sort")
print(repr(s2.groupby("tag").agg(m1=("s1", "mean"), x2=("s2", "max"), nrow=("s1", "size")).reset_index()))
_m("2_groupby_combine")
_m("3_using")
df3 = pd.read_csv(os.path.join(D, "people.csv"), parse_dates=["joined"], dtype={"name": "category", "city": "category"}); print(repr(df3))
_m("3_read_show")
print(repr(df3.describe(include="all")))
_m("3_describe")
print(repr(df3.groupby("city", observed=True).agg(mean_income=("income", "mean"), nrow=("income", "size")).reset_index()))
_m("3_groupby_combine")
